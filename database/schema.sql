-- Tracks4U - esquema relacional definitivo
-- Motor: PostgreSQL 14+ (Amazon RDS)
--
-- Basado en el diagrama de clases del pitch y ajustado con los acuerdos del equipo:
--   * Solo created_at / updated_at como metadatos de fila. ingested_at NO vive en las
--     tablas de negocio: lo agrega el pipeline en el data lake (Juanc).
--   * etl_watermark SI vive aqui: es la tabla de la que el pipeline de Juanc lee y a la que
--     escribe sus watermarks. La app Django no la lee ni la escribe.
--   * mood_tags (track) y tags (playlist) se conservan como arreglos de texto (TEXT[]).
--   * Los generos se normalizan en un catalogo compartido: genre + track_genre + artist_genre.
--     Reemplazan a las columnas artist.genres y track.genre del diagrama original.
--     track.subgenre se conserva como texto libre.
--   * updated_at lo mantiene un trigger en cada UPDATE (necesario para la carga incremental).
--   * "user" incluye app_role para identificar al sysadmin y last_login para Django.
--   * telemetry_event es el outbox de eventos de comportamiento (lo drena Lalo por HTTP).
--
-- Reglas del equipo:
--   * Este archivo es la fuente de verdad del esquema. Cualquier cambio se avisa a
--     Sergio, Juanc y Lalo y se refleja en AGENTS/contrato.md.
--   * Se ejecuta con el rol dueño de las tablas. Es re-ejecutable (IF NOT EXISTS).
--   * Las tablas internas de Django (django_*, auth_*) las crea "manage.py migrate"
--     en la misma base; no forman parte de este archivo ni se exponen al pipeline.

BEGIN;

-- ---------------------------------------------------------------------------
-- Funcion comun: actualiza updated_at en cada UPDATE
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------------
-- Entidades de negocio
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "user" (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username     VARCHAR(50)  NOT NULL UNIQUE,
    email        VARCHAR(255) NOT NULL UNIQUE,
    password     TEXT         NOT NULL,
    country      VARCHAR(100),
    birth_date   DATE,
    gender       VARCHAR(50)
                 CHECK (gender IS NULL OR gender IN ('FEMALE', 'MALE', 'NON_BINARY', 'PREFER_NOT_TO_SAY')),
    ethnicity    VARCHAR(100),
    app_role     VARCHAR(20)  NOT NULL DEFAULT 'user'
                 CHECK (app_role IN ('user', 'sysadmin')),
    last_login   TIMESTAMPTZ,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS artist (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT UNIQUE REFERENCES "user"(id) ON DELETE SET NULL,
    stage_name   VARCHAR(150) NOT NULL UNIQUE,
    bio          TEXT,
    country      VARCHAR(100),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Catalogo compartido de generos
CREATE TABLE IF NOT EXISTS genre (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(80)  NOT NULL UNIQUE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS track (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artist_id    BIGINT REFERENCES artist(id) ON DELETE SET NULL,
    title        VARCHAR(255) NOT NULL,
    subgenre     VARCHAR(100),
    language     VARCHAR(60),
    mood_tags    TEXT[],
    bpm          SMALLINT CHECK (bpm IS NULL OR bpm BETWEEN 1 AND 300),
    track_type   VARCHAR(50)
                 CHECK (track_type IS NULL OR track_type IN ('ORIGINAL', 'REMIX', 'COVER')),
    price        NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (price >= 0),
    audio_file   TEXT,          -- key relativa en S3 (no URL)
    cover_image  TEXT,          -- key relativa en S3 (no URL)
    duration_sec INTEGER CHECK (duration_sec IS NULL OR duration_sec >= 0),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Tablas puente de generos (sin timestamps)
CREATE TABLE IF NOT EXISTS track_genre (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_id     BIGINT NOT NULL REFERENCES track(id) ON DELETE CASCADE,
    genre_id     BIGINT NOT NULL REFERENCES genre(id) ON DELETE RESTRICT,
    UNIQUE (track_id, genre_id)
);

CREATE TABLE IF NOT EXISTS artist_genre (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artist_id    BIGINT NOT NULL REFERENCES artist(id) ON DELETE CASCADE,
    genre_id     BIGINT NOT NULL REFERENCES genre(id) ON DELETE RESTRICT,
    UNIQUE (artist_id, genre_id)
);

CREATE TABLE IF NOT EXISTS playlist (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id     BIGINT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
    name         VARCHAR(150) NOT NULL,
    description  TEXT,
    tags         TEXT[],
    cover_image  TEXT,          -- key relativa en S3
    is_public    BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS playlist_track (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id  BIGINT NOT NULL REFERENCES playlist(id) ON DELETE CASCADE,
    track_id     BIGINT NOT NULL REFERENCES track(id) ON DELETE CASCADE,
    position     INTEGER NOT NULL CHECK (position > 0),
    added_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (playlist_id, track_id),
    -- Diferida: permite reordenar (intercambiar posiciones) dentro de una transaccion.
    UNIQUE (playlist_id, position) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE IF NOT EXISTS "order" (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES "user"(id) ON DELETE RESTRICT,
    total_amount   NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0),
    currency       CHAR(3) NOT NULL DEFAULT 'USD',
    payment_method VARCHAR(60)
                   CHECK (payment_method IS NULL OR payment_method IN ('CARD', 'PAYPAL', 'PSE', 'OTHER')),
    status         VARCHAR(30) NOT NULL DEFAULT 'PLACED'
                   CHECK (status IN ('PLACED', 'COMPLETED', 'CANCELLED')),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS order_item (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT NOT NULL REFERENCES "order"(id) ON DELETE CASCADE,
    track_id    BIGINT NOT NULL REFERENCES track(id) ON DELETE RESTRICT,
    price_paid  NUMERIC(10,2) NOT NULL CHECK (price_paid >= 0),   -- precio congelado
    currency    CHAR(3) NOT NULL DEFAULT 'USD',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (order_id, track_id)
);

-- ---------------------------------------------------------------------------
-- Telemetria: outbox de eventos de comportamiento
-- La app inserta; el conector de Lalo lee por HTTP (GET /api/events/drain/) y confirma
-- (POST /api/events/ack/). Esta tabla NO se extrae por batch.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS telemetry_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- offset del outbox
    event_id    UUID         NOT NULL UNIQUE DEFAULT gen_random_uuid(), -- clave de deduplicacion
    event_type  VARCHAR(40)  NOT NULL,
    ts          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,        -- hora del evento
    session_id  VARCHAR(64)  NOT NULL,
    user_id     BIGINT REFERENCES "user"(id) ON DELETE SET NULL,
    device      VARCHAR(20)  NOT NULL DEFAULT 'unknown'
                CHECK (device IN ('web_desktop', 'web_mobile', 'web_tablet', 'unknown')),
    geo         JSONB,
    entrypoint  VARCHAR(20)  NOT NULL DEFAULT 'unknown'
                CHECK (entrypoint IN ('home', 'search', 'artist_profile', 'playlist',
                                      'track_page', 'library', 'external_link', 'unknown')),
    payload     JSONB        NOT NULL DEFAULT '{}'::jsonb,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,        -- recepcion
    acked_at    TIMESTAMPTZ                                             -- confirmacion de Lalo
);

-- ---------------------------------------------------------------------------
-- Control de ingesta incremental (pipeline de Juanc)
-- Una fila por entidad extraida. La escribe el pipeline; la app no la toca.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS etl_watermark (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_name      VARCHAR(150) NOT NULL UNIQUE,
    watermark_column VARCHAR(100) NOT NULL,
    last_value       TEXT,
    last_run_at      TIMESTAMPTZ,
    rows_loaded      BIGINT NOT NULL DEFAULT 0 CHECK (rows_loaded >= 0),
    status           VARCHAR(30) NOT NULL DEFAULT 'pending'
);

-- ---------------------------------------------------------------------------
-- Indices
-- ---------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_track_artist_id          ON track(artist_id);
CREATE INDEX IF NOT EXISTS idx_track_genre_genre_id     ON track_genre(genre_id);
CREATE INDEX IF NOT EXISTS idx_artist_genre_genre_id    ON artist_genre(genre_id);
CREATE INDEX IF NOT EXISTS idx_playlist_owner_id        ON playlist(owner_id);
CREATE INDEX IF NOT EXISTS idx_playlist_track_track_id  ON playlist_track(track_id);
CREATE INDEX IF NOT EXISTS idx_order_user_id            ON "order"(user_id);
CREATE INDEX IF NOT EXISTS idx_order_item_order_id      ON order_item(order_id);
CREATE INDEX IF NOT EXISTS idx_order_item_track_id      ON order_item(track_id);

-- updated_at: columna de control de la carga incremental
CREATE INDEX IF NOT EXISTS idx_user_updated_at           ON "user"(updated_at);
CREATE INDEX IF NOT EXISTS idx_artist_updated_at         ON artist(updated_at);
CREATE INDEX IF NOT EXISTS idx_genre_updated_at          ON genre(updated_at);
CREATE INDEX IF NOT EXISTS idx_track_updated_at          ON track(updated_at);
CREATE INDEX IF NOT EXISTS idx_playlist_updated_at       ON playlist(updated_at);
CREATE INDEX IF NOT EXISTS idx_playlist_track_updated_at ON playlist_track(updated_at);
CREATE INDEX IF NOT EXISTS idx_order_updated_at          ON "order"(updated_at);
CREATE INDEX IF NOT EXISTS idx_order_item_updated_at     ON order_item(updated_at);

-- Telemetria: pendientes de confirmar, purga y consultas por tipo
CREATE INDEX IF NOT EXISTS idx_telemetry_event_pending   ON telemetry_event(id) WHERE acked_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_telemetry_event_acked_at  ON telemetry_event(acked_at);
CREATE INDEX IF NOT EXISTS idx_telemetry_event_type_ts   ON telemetry_event(event_type, ts);

-- ---------------------------------------------------------------------------
-- Triggers updated_at (todas las tablas que tienen la columna)
-- ---------------------------------------------------------------------------
DROP TRIGGER IF EXISTS trg_user_set_updated_at ON "user";
CREATE TRIGGER trg_user_set_updated_at
BEFORE UPDATE ON "user"
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_artist_set_updated_at ON artist;
CREATE TRIGGER trg_artist_set_updated_at
BEFORE UPDATE ON artist
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_genre_set_updated_at ON genre;
CREATE TRIGGER trg_genre_set_updated_at
BEFORE UPDATE ON genre
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_track_set_updated_at ON track;
CREATE TRIGGER trg_track_set_updated_at
BEFORE UPDATE ON track
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_playlist_set_updated_at ON playlist;
CREATE TRIGGER trg_playlist_set_updated_at
BEFORE UPDATE ON playlist
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_playlist_track_set_updated_at ON playlist_track;
CREATE TRIGGER trg_playlist_track_set_updated_at
BEFORE UPDATE ON playlist_track
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_order_set_updated_at ON "order";
CREATE TRIGGER trg_order_set_updated_at
BEFORE UPDATE ON "order"
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_order_item_set_updated_at ON order_item;
CREATE TRIGGER trg_order_item_set_updated_at
BEFORE UPDATE ON order_item
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

